  let language = "ar";
  try { const saved=window.localStorage.getItem(storageKey); if(saved === "ar" || saved === "en") language=saved; } catch(_) {}
  function t(key, params={}){
    const text = messages[language][key] ?? messages.en[key] ?? key;
    return String(text).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => Object.prototype.hasOwnProperty.call(params,name) ? String(params[name]) : match);
  }
  function apply(root=document){
    if(root.querySelectorAll){
      root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent=t(el.getAttribute("data-i18n")); });
      for(const attribute of ["placeholder", "aria-label", "title"]){
        root.querySelectorAll("[data-i18n-"+attribute+"]").forEach(el => el.setAttribute(attribute,t(el.getAttribute("data-i18n-"+attribute))));
      }
    }
    document.documentElement.lang=language;
    document.documentElement.dir=language === "ar" ? "rtl" : "ltr";
    document.title=t("page.title");
    for(const choice of ["ar","en"]){
      const button=document.getElementById("language"+choice.toUpperCase());
      if(button){ button.setAttribute("aria-pressed",String(language===choice)); button.classList.toggle("active",language===choice); }
    }
  }
  function setLanguage(value){
    if(value !== "ar" && value !== "en") return;
    const changed=language!==value; language=value;
    try { window.localStorage.setItem(storageKey,value); } catch(_) {}
    apply();
    if(changed) window.dispatchEvent(new CustomEvent("aihub:languagechange",{detail:{language}}));
  }
